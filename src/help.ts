/**
 * Help and version output.
 */

import { CATALOG, catalogGroups } from './catalog.js';
import { GRADLE_WRAPPER_VERSION, INITIALIZR_BASE_URL, JAVA_VERSIONS, VERSIONS } from './versions.js';

/** Long help text shown by `--help`. */
export function helpText(): string {
  const dependencyList = catalogGroups()
    .map(({ group, items }) => `    ${group.padEnd(11)} ${items.map((d) => d.id).join(', ')}`)
    .join('\n');

  return `create-jvm — scaffold Maven, Gradle and Spring Boot projects

Usage
  create-jvm [project-name] [options]

  Run without arguments to launch the interactive wizard, which mirrors the
  IntelliJ IDEA "New Project" dialog.

Project type
  --maven                     Plain Maven project
  --gradle                    Plain Gradle project
  --spring-boot, --boot       Spring Boot project (via start.spring.io)
  --template, -t <spec>       Generate from a remote git template
                              gh:owner/repo[/subdir][#ref]
                              gitlab:owner/repo, bitbucket:owner/repo
                              https://github.com/owner/repo

Build
  --build-tool <maven|gradle> Build system (default: maven)
  --dsl <groovy|kotlin>       Gradle DSL (default: groovy)
  --packaging <jar|war>       Archive type (default: jar)
  --config-format <fmt>       Spring Boot config file: properties | yaml
                              (default: properties)
  --module <name>             Add a module; repeatable, implies --multi-module
  --multi-module              Generate an aggregator plus modules
  --install                   Run a build after generating
  --no-install                Skip the post-generation build

Coordinates
  --group-id <id>             Maven groupId (default: com.example)
  --artifact-id <id>          Maven artifactId (default: derived from the name)
  --package <name>            Base package (default: derived from groupId)
  --project-version <v>       Project version (default: 0.0.1-SNAPSHOT)
  --name <name>               Project name
  --description <text>        Project description

Language and platform
  --language, --lang <l>      java | kotlin | groovy (default: java)
  --java-version <v>          Java release: ${JAVA_VERSIONS.join(', ')} (default: 21)
  --kotlin-version <v>        Kotlin version (default: ${VERSIONS.kotlin})
  --boot-version <v>          Spring Boot version (default: the Initializr default)

Dependencies
  --dep <id[,id...]>          Add dependencies from the catalog; repeatable
  --boot-dep <id[,id...]>     Add Spring Boot starters by Initializr id
  --dependencies              Alias for --dep

  Catalog ids (or use raw "groupId:artifactId[:version]"):

${dependencyList}

Behaviour
  --git / --no-git            Run git init (default: yes when git is available)
  --dry-run                   Print the file list without writing anything
  --force, -f                 Write into a non-empty directory
  --yes, -y, --no-input       Never prompt; use defaults for anything unset
  --json                      Machine readable output
  --no-color                  Disable coloured output
  --help, -h                  Show this help
  --version, -v               Show the version

Examples
  create-jvm                                  Interactive wizard
  create-jvm my-app --maven --dep lombok      Maven project with Lombok
  create-jvm api --spring-boot --boot-dep web,data-jpa,actuator
  create-jvm svc --gradle --dsl kotlin --language kotlin
  create-jvm lib --maven --module core --module web
  create-jvm app -t gh:spring-projects/spring-petclinic

Spring Boot projects are generated by ${INITIALIZR_BASE_URL};
Gradle projects use the Gradle ${GRADLE_WRAPPER_VERSION} wrapper.
`;
}

/** Short usage line shown after an argument error. */
export function usageText(): string {
  return 'Usage: create-jvm [project-name] [options]\nRun "create-jvm --help" for the full option list.';
}

/** Number of catalog entries, used in summaries. */
export function catalogSize(): number {
  return CATALOG.length;
}
