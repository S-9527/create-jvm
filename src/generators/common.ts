/**
 * Files every generated project shares.
 */

import type { BuildTool, ProjectConfig } from '../types.js';

/** `.gitignore` tailored to the build tool and IDE conventions. */
export function renderGitignore(buildTool: BuildTool): string {
  const common = `# Compiled output
target/
build/
out/
bin/
*.class

# Logs
*.log
logs/

# Package files
*.jar
*.war
*.nar
*.ear
*.zip
*.tar.gz
*.rar

# IDE
.idea/
*.iml
*.ipr
*.iws
.vscode/
*.swp
.settings/
.classpath
.project

# OS
.DS_Store
Thumbs.db
`;

  const gradle = `
# Gradle
.gradle/
!gradle/wrapper/gradle-wrapper.jar
`;

  return buildTool === 'gradle' ? `${common}${gradle}` : common;
}

/** A short `README.md` describing the generated project. */
export function renderReadme(config: ProjectConfig, buildTool: BuildTool): string {
  const build = buildTool === 'maven' ? './mvnw' : './gradlew';
  const runCommand =
    config.packaging === 'war'
      ? `${build} package`
      : buildTool === 'maven'
        ? `${build} exec:java`
        : `${build} run`;
  const testCommand = `${build} test`;

  return `# ${config.name}

${config.description || 'A JVM project generated by create-jvm.'}

## Requirements

- JDK ${config.javaVersion} or newer

## Build

\`\`\`bash
${build} package
\`\`\`

## Test

\`\`\`bash
${testCommand}
\`\`\`

## Run

\`\`\`bash
${runCommand}
\`\`\`

## Layout

\`\`\`
${config.language === 'java' ? 'src/main/java' : config.language === 'kotlin' ? 'src/main/kotlin' : 'src/main/groovy'}   application sources
src/main/resources   resources
src/test              tests
\`\`\`

---

Generated with [create-jvm](https://github.com/S-9527/create-jvm).
`;
}

/** A Spring Boot flavoured `README.md`. */
export function renderBootReadme(config: ProjectConfig, buildTool: BuildTool): string {
  const build = buildTool === 'maven' ? './mvnw' : './gradlew';
  return `# ${config.name}

${config.description || 'A Spring Boot application generated by create-jvm.'}

## Requirements

- JDK ${config.javaVersion} or newer

## Run

\`\`\`bash
${build} spring-boot:run
\`\`\`

Or on Gradle:

\`\`\`bash
${build} bootRun
\`\`\`

## Test

\`\`\`bash
${build} test
\`\`\`

## Package

\`\`\`bash
${build} package
\`\`\`

---

Generated with [create-jvm](https://github.com/S-9527/create-jvm) via
[Spring Initializr](https://start.spring.io).
`;
}

/** A `settings.xml` free `.mvn/jvm.config` keeping builds predictable. */
export function renderMavenJvmConfig(): string {
  return '-Dfile.encoding=UTF-8\n';
}
